function [fig, ax] = viz_figure(titleText, subtitleText)
% Creates the hidden 1280x720 figure with a left-aligned title, subtitle and one styled axes.
st = viz_style();
fig = figure('Visible', 'off', 'Color', 'w', 'Units', 'pixels', ...
    'Position', [60 60 1280 720], 'InvertHardcopy', 'off', 'PaperPositionMode', 'auto');
annotation(fig, 'textbox', [0.035 0.885 0.93 0.085], 'String', titleText, ...
    'EdgeColor', 'none', 'FitBoxToText', 'off', 'FontName', st.font_title, ...
    'FontSize', st.fs_title, 'Color', st.ink, 'HorizontalAlignment', 'left', ...
    'VerticalAlignment', 'middle', 'Interpreter', 'none');
annotation(fig, 'textbox', [0.035 0.825 0.93 0.06], 'String', subtitleText, ...
    'EdgeColor', 'none', 'FitBoxToText', 'off', 'FontName', st.font, ...
    'FontSize', st.fs_sub, 'Color', st.ink2, 'HorizontalAlignment', 'left', ...
    'VerticalAlignment', 'middle', 'Interpreter', 'none');
ax = axes(fig, 'Position', [0.075 0.13 0.86 0.645]);
viz_axes(ax);
end
